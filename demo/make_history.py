def sessions_per_day(day: date) -> int:
    """Two a day on weekdays, one at the weekend: busy, not impossible."""
    return 1 if day.weekday() >= 5 else 2


def build_history(
    end: date,
    days: int,
    seed: int,
    sheet: PriceSheet,
) -> tuple[list[Logged], dict[str, Any]]:
    """Build every session in the window and summarise it."""
    rng = random.Random(seed)
    start = end - timedelta(days=days - 1)
    rows: list[Logged] = []
    sessions: list[dict[str, Any]] = []
    per_day: dict[str, dict[str, Any]] = {}

    for offset in range(days):
        day = start + timedelta(days=offset)
        for slot in range(sessions_per_day(day)):
            task, files, result = TASKS[(offset * 2 + slot) % len(TASKS)]
            session_id = f"{day.isoformat()}-{task.replace(' ', '-')[:40]}-{slot + 1}"
            count = rng.randint(18, 46)
            session_rows = build_session(
                rng,
                sheet,
                task=task,
                session_id=session_id,
                day=day,
                start_hour=9 + slot * 4,
                turns=count,
            )
            rows.extend(session_rows)
            sessions.append(_session_summary(session_rows, sheet, day, task, files, result))

            bucket = per_day.setdefault(
                day.isoformat(),
                {
                    "date": day.isoformat(),
                    "sessions": 0,
                    "requests": 0,
                    "switches": 0,
                    "saving_usd": 0.0,
                },
            )
            bucket["sessions"] += 1
            bucket["requests"] += len(session_rows)
            bucket["switches"] += sum(1 for r in session_rows if r.decision.action == "SWITCH")
            bucket["saving_usd"] += _saving_of(session_rows, sheet)

    summary = {
        "note": SYNTHETIC_NOTE,
        "generator": "demo/make_history.py",
        "seed": seed,
        "window": {"start": start.isoformat(), "end": end.isoformat(), "days": days},
        "price_sheet": {
            "path": PRICE_SHEET_LABEL,
            "simulated": sheet.simulated,
            "date": sheet.date,
        },
        "totals": _totals(sessions, rows, sheet),
        "weeks": _weeks(sessions),
        "days": [per_day[key] for key in sorted(per_day)],
        "sessions": sessions,
    }
    return rows, summary


def _price_of(model: str, usage: Usage, sheet: PriceSheet) -> float:
    usd = compute_cost(model, usage, sheet).usd
    if usd is None:
        raise ValueError(f"cannot price {model} with sheet {sheet.date}")
    return usd


def _saving_of(rows: list[Logged], sheet: PriceSheet) -> float:
    strong = sum(_price_of(STRONG, r.usage, sheet) for r in rows)
    actual = sum(_price_of(r.model_used, r.usage, sheet) for r in rows)
    return strong - actual


def _session_summary(
    rows: list[Logged],
    sheet: PriceSheet,
    day: date,
    task: str,
    files: tuple[str, ...],
    result: str,
) -> dict[str, Any]:
    strong = sum(_price_of(STRONG, r.usage, sheet) for r in rows)
    actual = sum(_price_of(r.model_used, r.usage, sheet) for r in rows)
    switches = sum(1 for r in rows if r.decision.action == "SWITCH")
    return {
        "date": day.isoformat(),
        "task": task,
        "files": list(files),
        "result": result,
        "session_id": rows[0].session_id,
        "requests": len(rows),
        "switches": switches,
        "cheap_requests": sum(1 for r in rows if r.model_used == CHEAP),
        "input_tokens": sum(r.usage.input_tokens or 0 for r in rows),
        "output_tokens": sum(r.usage.output_tokens or 0 for r in rows),
        "cached_input_tokens": sum(r.usage.cached_input_tokens or 0 for r in rows),
        "all_strong_usd": round(strong, 6),
        "actual_mix_usd": round(actual, 6),
        "saving_usd": round(strong - actual, 6),
        "saving_pct": round(100.0 * (strong - actual) / strong, 2) if strong else None,
        "first_ts": rows[0].ts,
        "last_ts": rows[-1].ts,
    }


def _totals(
    sessions: list[dict[str, Any]],
    rows: list[Logged],
    sheet: PriceSheet,
) -> dict[str, Any]:
    strong = sum(_price_of(STRONG, r.usage, sheet) for r in rows)
    actual = sum(_price_of(r.model_used, r.usage, sheet) for r in rows)
    return {
        "sessions": len(sessions),
        "requests": len(rows),
        "switches": sum(1 for r in rows if r.decision.action == "SWITCH"),
        "cheap_requests": sum(1 for r in rows if r.model_used == CHEAP),
        "input_tokens": sum(r.usage.input_tokens or 0 for r in rows),
        "output_tokens": sum(r.usage.output_tokens or 0 for r in rows),
        "cached_input_tokens": sum(r.usage.cached_input_tokens or 0 for r in rows),
        "all_strong_usd": round(strong, 6),
        "actual_mix_usd": round(actual, 6),
        "saving_usd": round(strong - actual, 6),
        "saving_pct": round(100.0 * (strong - actual) / strong, 2) if strong else None,
        "tasks_completed": len(sessions),
        "decisions": _decision_counts(rows),
    }


def _decision_counts(rows: list[Logged]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for row in rows:
        counts[row.decision.reason] = counts.get(row.decision.reason, 0) + 1
    return dict(sorted(counts.items(), key=lambda item: (-item[1], item[0])))


def _weeks(sessions: list[dict[str, Any]]) -> list[dict[str, Any]]:
    buckets: dict[str, dict[str, Any]] = {}
    for session in sessions:
        iso = date.fromisoformat(session["date"]).isocalendar()
        key = f"{iso[0]}-W{iso[1]:02d}"
        bucket = buckets.setdefault(
            key,
            {
                "week": key,
                "sessions": 0,
                "requests": 0,
                "switches": 0,
                "all_strong_usd": 0.0,
                "actual_mix_usd": 0.0,
                "saving_usd": 0.0,
            },
        )
        bucket["sessions"] += 1
        bucket["requests"] += session["requests"]
        bucket["switches"] += session["switches"]
        bucket["all_strong_usd"] += session["all_strong_usd"]
        bucket["actual_mix_usd"] += session["actual_mix_usd"]
        bucket["saving_usd"] += session["saving_usd"]
    out = []
    for key in sorted(buckets):
        bucket = buckets[key]
        strong = bucket["all_strong_usd"]
        bucket["saving_usd"] = round(bucket["saving_usd"], 6)
        bucket["all_strong_usd"] = round(strong, 6)
        bucket["actual_mix_usd"] = round(bucket["actual_mix_usd"], 6)
        bucket["saving_pct"] = round(100.0 * bucket["saving_usd"] / strong, 2) if strong else None
        out.append(bucket)
    return out


