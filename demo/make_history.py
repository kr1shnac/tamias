def write_log(path: Path, rows: list[Logged], sheet: PriceSheet) -> None:
    """Write the request log with the real Store, stamped simulated."""
    if path.exists():
        path.unlink()
    store = Store(path)
    try:
        for row in rows:
            store.log_request(
                ts=row.ts,
                session_id=row.session_id,
                model_requested=STRONG,
                model_used=row.model_used,
                usage=row.usage,
                cost=CostBreakdown(
                    usd=row.cost_usd,
                    formula="synthetic: priced by demo/make_history.py with tamias.pricing",
                    price_sheet_date=sheet.date,
                ),
                latency_ms=row.latency_ms,
                status="ok",
                decision=row.decision,
                price_sheet=PRICE_SHEET_LABEL,
                price_simulated=True,
            )
    finally:
        store.close()


def render_summary_markdown(summary: dict[str, Any]) -> str:
    totals = summary["totals"]
    window = summary["window"]
    lines = [
        "# Three weeks of agent history -- SYNTHETIC",
        "",
        f"> {SYNTHETIC_NOTE}",
        "",
        f"Window **{window['start']} .. {window['end']}** ({window['days']} days), "
        f"seed `{summary['seed']}`, priced with `{summary['price_sheet']['path']}` "
        f"(simulated = {str(summary['price_sheet']['simulated']).lower()}).",
        "",
        "## Headline",
        "",
        "| | |",
        "| --- | --- |",
        f"| Coding sessions | {totals['sessions']} |",
        f"| Requests logged | {totals['requests']} |",
        f"| Requests routed to the cheap model | {totals['cheap_requests']} "
        f"({100.0 * totals['cheap_requests'] / totals['requests']:.0f}%) |",
        f"| Input / output / cached tokens | {totals['input_tokens']:,} / "
        f"{totals['output_tokens']:,} / {totals['cached_input_tokens']:,} |",
        f"| Same traffic, all on the strong model | ${totals['all_strong_usd']:.4f} |",
        f"| Same traffic, the mix the router chose | ${totals['actual_mix_usd']:.4f} |",
        f"| **List-price saving** | **${totals['saving_usd']:.4f} "
        f"({totals['saving_pct']:.1f}%)** |",
        "",
        "## By week",
        "",
        "| week | sessions | requests | switches | all strong | actual mix | saving |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for week in summary["weeks"]:
        lines.append(
            f"| {week['week']} | {week['sessions']} | {week['requests']} | "
            f"{week['switches']} | ${week['all_strong_usd']:.4f} | "
            f"${week['actual_mix_usd']:.4f} | ${week['saving_usd']:.4f} "
            f"({week['saving_pct']:.1f}%) |"
        )

    lines += [
        "",
        "## Every session",
        "",
        "| date | task | reqs | switches | all strong | actual mix | saving | result |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for session in summary["sessions"]:
        lines.append(
            f"| {session['date']} | {session['task']} | {session['requests']} | "
            f"{session['switches']} | ${session['all_strong_usd']:.4f} | "
            f"${session['actual_mix_usd']:.4f} | ${session['saving_usd']:.4f} | "
            f"{session['result']} |"
        )

    lines += [
        "",
        "## What the router decided, and why",
        "",
        "| reason | requests |",
        "| --- | ---: |",
    ]
    for reason, count in totals["decisions"].items():
        lines.append(f"| {reason} | {count} |")

    lines += [
        "",
        "## Honest limits",
        "",
        "- **Synthetic.** No request here was sent to a model. The tasks, the token",
        "  counts and the outcomes are invented by `demo/make_history.py`.",
        "- **Simulated prices.** `prices.simulated.toml` declares `simulated = true`, so",
        "  every amount above is stamped `SIMULATED PRICES, NOT REAL SAVINGS` wherever",
        "  `tamias report` prints it. The rates are made up; the arithmetic is the real",
        "  `tamias.pricing.compute_cost`.",
        "- **List prices, not a bill.** The saving is the gap between pricing the same",
        "  tokens on the strong model and pricing them on the model that answered. It is",
        "  not money that was spent, and not a measurement of quality.",
        "- **The history does not prove quality.** `result` is a field in this script, not",
        "  a test run. Nothing here shows the cheap model did the work well.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output directory")
    parser.add_argument("--days", type=int, default=21, help="window length in days")
    parser.add_argument("--seed", type=int, default=7, help="RNG seed; same seed, same data")
    parser.add_argument(
        "--end",
        type=date.fromisoformat,
        default=date.today(),
        help="last day of the window, YYYY-MM-DD (default: today)",
    )
    parser.add_argument("--prices", type=Path, default=DEFAULT_PRICES, help="price sheet")
    args = parser.parse_args(argv)

    if args.days < 1:
        parser.error("--days must be at least 1")

    sheet = load_price_sheet(args.prices)
    rows, summary = build_history(args.end, args.days, args.seed, sheet)

    args.out.mkdir(parents=True, exist_ok=True)
    db_path = args.out / "agent-3weeks.db"
    json_path = args.out / "agent-3weeks.json"
    md_path = args.out / "SUMMARY.md"

    write_log(db_path, rows, sheet)
    json_path.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    md_path.write_text(render_summary_markdown(summary), encoding="utf-8")

    totals = summary["totals"]
    print(f"make_history: wrote {db_path} ({totals['requests']} requests)")
    print(f"make_history: wrote {json_path}")
    print(f"make_history: wrote {md_path}")
    print(f"make_history: window {summary['window']['start']} .. {summary['window']['end']}")
    print(
        f"make_history: {totals['sessions']} sessions, {totals['requests']} requests, "
        f"{totals['switches']} switches, {totals['cheap_requests']} on the cheap model"
    )
    print(
        f"make_history: all strong ${totals['all_strong_usd']:.4f}, actual mix "
        f"${totals['actual_mix_usd']:.4f}, saving ${totals['saving_usd']:.4f} "
        f"({totals['saving_pct']:.1f}%)"
    )
    print("make_history: SYNTHETIC DATA, SIMULATED PRICES, NOT REAL SAVINGS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
