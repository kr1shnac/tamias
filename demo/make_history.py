EASY_TOOLS = ("bash", "read", "grep", "ls", "glob")
HARD_TOOLS = ("edit_file", "write")

Bash_PASS = "$ pytest -q\n{passed} passed in {seconds:.2f}s"
Bash_GREP = "$ grep -rn '{needle}' src/\n{hits}"
Bash_LS = "$ ls -la src/\n{listing}"
Bash_SEED = "$ python -m pytest tests/ -x -q"


@dataclass(frozen=True, slots=True)
class Turn:
    """One request the invented agent session makes, in order."""

    kind: str  # "user" | "easy" | "hard" | "error"
    tool: str


@dataclass(frozen=True, slots=True)
class Logged:
    """A row the summary is built from, before it reaches the Store."""

    session_id: str
    ts: str
    decision: Decision
    model_used: str
    usage: Usage
    cost_usd: float | None
    latency_ms: int


# --------------------------------------------------------------------------
# Turn plans
# --------------------------------------------------------------------------


def plan_turns(rng: random.Random, turns: int) -> list[Turn]:
    """A session shaped like a real coding loop: look, change, run the tests.

    The loop is what makes the router produce a striped timeline.  Reading and
    grepping are easy-tool turns the router may switch; the edit is not; the
    test run is easy again but often comes back red, and a red run is exactly
    what rule 2 keeps on the strong model.
    """
    plan = [Turn("user", "")]
    while len(plan) < turns:
        # Reading and grepping are the cheap-tool turns; there are always two
        # of them before a change, and the test run after it is easy too.
        plan.append(Turn("easy", rng.choice(EASY_TOOLS)))
        plan.append(Turn("easy", rng.choice(EASY_TOOLS)))
        plan.append(Turn("hard", rng.choice(HARD_TOOLS)))
        if rng.random() < 0.35:
            plan.append(Turn("error", "bash"))
        plan.append(Turn("easy", "bash"))
        if rng.random() < 0.5:
            plan.append(Turn("easy", rng.choice(("grep", "glob"))))
    return plan[:turns]


# --------------------------------------------------------------------------
# Message shapes -- the same shapes dry_run_client.py sends, because that is
# what the router branches on.
# --------------------------------------------------------------------------


def _source_lines(rng: random.Random, lines: int) -> str:
    samples = (
        "def {name}({args}):\n    {body}\n",
        "class {name}:\n    def __init__(self, store):\n        self.store = store\n",
        '    assert {left} == {right}, f"{{left}} != {{right}}"\n',
        "# {name}: regenerated by the build\n",
    )
    out = []
    for _ in range(lines):
        template = rng.choice(samples)
        out.append(
            template.format(
                name=rng.choice(("parse", "render", "fetch", "merge", "validate", "retry")),
                args=rng.choice(("value", "payload, raw", "rows, limit=100", "key")),
                body=rng.choice(("return value", "raise ValueError(key)", "self.store.put(value)")),
                left=rng.choice(("total", "len(rows)", "status")),
                right=rng.choice(("0", "len(rows)", '"ok"')),
            )
        )
    return "".join(out)


def _tool_payload(rng: random.Random, turn: Turn, task: str) -> str:
    """The tool result text.  Its size is what grows the context window."""
    if turn.kind == "error":
        return (
            "Traceback (most recent call last):\n"
            f'  File "tests/test_{task.split()[0]}.py", line 12, in test_flow\n'
            "    assert result.ok is True\n"
            "AssertionError: assert False is True\n"
            "FAILED tests/test_flow.py::test_flow - AssertionError\n"
        )
    if turn.tool == "read":
        return _source_lines(rng, rng.randint(60, 320))
    if turn.tool == "grep":
        return "\n".join(
            f"src/{rng.choice(('api', 'jobs', 'billing', 'cache'))}/"
            f"{rng.choice(('views', 'runner', 'ledger', 'lock'))}.py:{rng.randint(10, 400)}:"
            f"    {rng.choice(('result = fn(value)', 'if not rows: return', 'log.info(key)'))}"
            for _ in range(rng.randint(8, 60))
        )
    if turn.tool == "ls":
        return "\n".join(
            f"{rng.choice(('-rw-r--r--', 'drwxr-xr-x'))} 1 krish krish {rng.randint(400, 90000)} "
            f"{rng.choice(('app.py', 'test_flow.py', 'index.sql', 'runner.py'))}"
            for _ in range(rng.randint(5, 40))
        )
    if turn.tool == "glob":
        return "\n".join(
            f"src/pkg/{rng.choice(('a', 'b', 'c', 'd'))}_{rng.randint(1, 9)}.py"
            for _ in range(rng.randint(6, 30))
        )
    if turn.tool == "bash":
        failed = "$ python -m pytest tests/ -q\n"
        failed += (
            f"{rng.randint(1, 4)} failed, {rng.randint(2, 30)} passed "
            f"in {rng.uniform(0.5, 5.0):.2f}s"
        )
        return rng.choice(
            (
                Bash_PASS.format(passed=rng.randint(6, 40), seconds=rng.uniform(0.4, 6.0)),
                "$ ruff check src/\nAll checks passed!",
                Bash_SEED,
                failed,
                Bash_GREP.format(
                    needle=rng.choice(("TODO", "raise NotImplementedError", "session_id")),
                    hits="\n".join(
                        f"src/{rng.choice(('api', 'jobs'))}/{rng.choice(('views', 'runner'))}.py:"
                        f"{rng.randint(10, 300)}:{rng.choice(('# TODO: split this', 'pass'))}"
                        for _ in range(rng.randint(3, 20))
                    ),
                ),
                Bash_LS.format(
                    listing="\n".join(
                        f"-rw-r--r-- 1 krish krish {rng.randint(900, 40000)} "
                        f"{rng.choice(('main.py', 'schema.py', 'test_api.py'))}"
                        for _ in range(rng.randint(4, 25))
                    )
                ),
            )
        )
    # edit_file / write: the change landed.
    return f"applied patch to {turn.tool} ({rng.randint(1, 3)} file(s) changed)"


def _assistant_payload(rng: random.Random, turn: Turn) -> str:
    """The assistant message: a plan, a tool call, or the patch it wrote."""
    if turn.kind == "user":
        return (
            "Reading the failing test first, then I'll make the smallest change that "
            "makes it pass and re-run the suite.\n"
        )
    if turn.kind == "error":
        return (
            "The assertion is wrong about the null case: the parser returns None before "
            "the coercion runs. I'll move the coercion ahead of the check and add a test.\n"
        )
    if turn.kind == "hard":
        return _source_lines(rng, rng.randint(12, 90))
    return rng.choice(
        (
            "Running the suite again.\n",
            "That file does not own this; checking the caller.\n",
            "Found it -- the guard is in the caller.\n",
            "Keeping the change small; no schema edit needed.\n",
        )
    )


def _assistant_message(rng: random.Random, turn: Turn, call_id: str) -> dict[str, Any]:
    if turn.kind == "user":
        return {"role": "assistant", "content": _assistant_payload(rng, turn)}
    return {
        "role": "assistant",
        "content": None,
        "tool_calls": [
            {
                "id": call_id,
                "type": "function",
                "function": {
                    "name": turn.tool,
                    "arguments": _assistant_payload(rng, turn),
                },
            }
        ],
    }


def _chars(value: Any) -> int:
    return len(json.dumps(value, ensure_ascii=False))


def _tokens(chars: int) -> int:
    """Token count for a byte length: the usual ~4 chars per token, rounded up.

    Rounded up, never down: an estimate that reads high is a demo that admits
    it is an estimate; one that reads low claims more precision than a
    character count can give.
    """
    return max(1, math.ceil(chars / 4))


# --------------------------------------------------------------------------
# One session
# --------------------------------------------------------------------------


def build_session(
    rng: random.Random,
    sheet: PriceSheet,
    task: str,
    session_id: str,
    day: date,
    start_hour: int,
    turns: int,
) -> list[Logged]:
    """Run one invented session through the real router and the real pricer."""
    plan = plan_turns(rng, turns)
    messages: list[dict[str, Any]] = []
    current_model = STRONG
    clock = datetime(day.year, day.month, day.day, start_hour, rng.randint(0, 40), 0)
    previous_input_tokens = 0
    out: list[Logged] = []

    for index, turn in enumerate(plan):
        if turn.kind == "user":
            messages.append({"role": "user", "content": task})
        else:
            call_id = f"call_{session_id}_{index}"
            messages.append(_assistant_message(rng, turn, call_id))
            messages.append(
                {
                    "role": "tool",
                    "tool_call_id": call_id,
                    "name": turn.tool,
                    "content": _tool_payload(rng, turn, task),
                }
            )

        decision = decide(
            {"model": STRONG, "messages": messages},
            SessionState(session_id=session_id, request_index=index, current_model=current_model),
            CONFIG,
        )
        model_used = decision.target_model if decision.action == "SWITCH" else STRONG
        current_model = model_used

        input_tokens = _tokens(_chars(messages))
        # A prefix cache serves what the previous request had already seen, so
        # the cached count is last turn's input and never more than this one's.
        cached = min(previous_input_tokens, input_tokens) if index >= 2 else 0
        output_tokens = _tokens(_chars(messages[-1])) + rng.randint(10, 180)
        previous_input_tokens = input_tokens

        usage = Usage(
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            cached_input_tokens=cached,
            cache_write_tokens=0,
        )
        cost = compute_cost(model_used, usage, sheet)
        clock += timedelta(seconds=rng.randint(8, 120))
        out.append(
            Logged(
                session_id=session_id,
                ts=clock.isoformat(sep=" "),
                decision=decision,
                model_used=model_used,
                usage=usage,
                cost_usd=cost.usd,
                latency_ms=rng.randint(250, 9000)
                if model_used == STRONG
                else rng.randint(120, 2400),
            )
        )
    return out


