#!/usr/bin/env python3
"""Generate three weeks of synthetic agent history for the demo.

**SYNTHETIC DATA.  NOTHING IN THE OUTPUT WAS EVER SENT TO A MODEL.**

This script invents a fortnight-and-a-half of "the agent coded all day" sessions
so the demo has a history to show: which tasks were attempted, how many requests
each one took, how many the router moved to the cheap model, and what the same
traffic would have cost on the strong model alone.  It writes

    demo/history/agent-3weeks.db     request log, same schema `tamias serve` writes
    demo/history/agent-3weeks.json   per-session and per-day summary
    demo/history/SUMMARY.md          the same summary as a table

and every file it produces says SYNTHETIC on the face of it.

What makes it a *demo* of tamias rather than a made-up table:

* the request rows are written by the real :class:`tamias.store.Store`, so
  ``tamias report``, ``tamias.dashboard`` and every other reader see a normal
  log and need no special case;
* the routing decisions come from the real :func:`tamias.router.decide` fed the
  real message shapes an agent session produces, so the SWITCH/STAY mix is the
  router's own behaviour, not a coin flip;
* the costs come from the real :func:`tamias.pricing.compute_cost` against
  ``prices.simulated.toml``, whose ``simulated = true`` is what stamps
  ``SIMULATED PRICES, NOT REAL SAVINGS`` on every line ``tamias report``
  prints.  The rates are invented, the arithmetic is not;
* token counts are derived from the message bytes the script actually builds
  (``ceil(chars / 4)``) with prefix caching modelled as "the context the previous
  request already had", so input, cached and output counts agree with each other
  instead of being three unrelated random numbers.

Usage::

    .venv/bin/python demo/make_history.py
    .venv/bin/python demo/make_history.py --end 2026-10-05 --days 21 --seed 7

The output is deterministic for a given ``--seed``/``--days``/``--end``, so a
regeneration reproduces the numbers quoted in the demo.
"""

